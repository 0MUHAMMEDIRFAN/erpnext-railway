#!/usr/bin/env bash
set -Eeuo pipefail

versions=/opt/erpnext/versions.json
manifest=/opt/erpnext/apps.json
jq -e '
  (.apps | type == "array") and
  (all(.apps[]; (.name | test("^[a-z][a-z0-9_]*$")) and
    (.name != "frappe" and .name != "erpnext") and
    (.url | test("^https://github\\.com/[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$")) and
    (.ref | test("^[A-Za-z0-9][A-Za-z0-9._/-]*$")) and
    (.commit | test("^[0-9a-f]{40}$")) and (.install_on_site | type == "boolean"))) and
  ((.apps | map(.name) | unique | length) == (.apps | length))
' "$manifest" >/dev/null
jq -e --slurpfile versions "$versions" '
  any(.apps[]; .name == "hrms" and .url == $versions[0].hrms.repository
    and .ref == $versions[0].hrms.ref and .commit == $versions[0].hrms.commit)
' "$manifest" >/dev/null

export GIT_TERMINAL_PROMPT=0
if [[ -s /run/secrets/app_git_token ]]; then
    export GIT_CONFIG_COUNT=1
    export GIT_CONFIG_KEY_0=credential.https://github.com.helper
    # Git invokes this for github.com only. Neither the URL nor Git config contains the token.
    export GIT_CONFIG_VALUE_0='!f() { if [ "$1" = get ]; then printf "username=x-access-token\npassword="; cat /run/secrets/app_git_token; printf "\n"; fi; }; f'
fi

verify_commit() {
    local name=$1 expected=$2
    [[ "$(git -C "apps/$name" rev-parse HEAD)" == "$expected" ]] || {
        echo "Commit mismatch for $name" >&2
        exit 1
    }
}

bench init --frappe-path "$(jq -r .frappe.repository "$versions")" \
    --frappe-branch "$(jq -r .frappe.ref "$versions")" \
    --no-procfile --no-backups --skip-redis-config-generation --skip-assets frappe-bench
cd frappe-bench
verify_commit frappe "$(jq -r .frappe.commit "$versions")"

bench get-app --skip-assets --branch "$(jq -r .erpnext.ref "$versions")" \
    "$(jq -r .erpnext.repository "$versions")"
verify_commit erpnext "$(jq -r .erpnext.commit "$versions")"

apps=$(jq -r '.apps[] | [.name,.url,.ref,.commit] | @tsv' "$manifest")
while IFS=$'\t' read -r name url ref commit; do
    bench get-app --skip-assets --branch "$ref" "$name" "$url"
    verify_commit "$name" "$commit"
done <<< "$apps"
unset GIT_CONFIG_COUNT GIT_CONFIG_KEY_0 GIT_CONFIG_VALUE_0

bench build
env/bin/python -c 'import frappe, erpnext, hrms'
test -L sites/assets/hrms
test -n "$(find -L sites/assets/hrms/dist -type f -name '*.js' -print -quit)"
mkdir built_sites
mv sites/assets sites/apps.json sites/apps.txt built_sites/
find apps -mindepth 2 -maxdepth 2 -name .git -exec rm -rf -- {} +
# Asset links generated by Bench point into apps/, which stays at the same absolute path.
